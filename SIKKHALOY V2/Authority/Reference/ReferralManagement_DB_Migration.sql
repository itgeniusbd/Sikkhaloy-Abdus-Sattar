INSERT INTO AAP_Reference_Commission (
    ReferenceID, Reference_School_ID, InvoiceID, SchoolID,
    Commission_Amount, Commission_Percentage, ServiceCharge_Amount, Commission_Date
)
SELECT 
    rs.ReferenceID,
    rs.Reference_School_ID,
    i.InvoiceID,
    i.SchoolID,
    CAST(i.TotalAmount * rs.Percentage / 100.0 AS DECIMAL(18,2)) AS Commission_Amount,
    rs.Percentage AS Commission_Percentage,
    i.TotalAmount AS ServiceCharge_Amount,
    CAST(ISNULL(i.LastPaidDate, i.IssuDate) AS DATE) AS Commission_Date
FROM AAP_Reference_School rs
INNER JOIN AAP_Invoice i ON i.SchoolID = rs.SchoolID
    AND i.IsPaid = 1
    AND (rs.End_Reference_Date IS NULL OR CAST(ISNULL(i.LastPaidDate, i.IssuDate) AS DATE) <= rs.End_Reference_Date)
    AND i.InvoiceCategoryID = (
        SELECT TOP 1 InvoiceCategoryID FROM AAP_Invoice_Category WHERE InvoiceCategory = N'Service Charge'
    )
WHERE NOT EXISTS (
    SELECT 1 FROM AAP_Reference_Commission rc 
    WHERE rc.InvoiceID = i.InvoiceID AND rc.ReferenceID = rs.ReferenceID
);

