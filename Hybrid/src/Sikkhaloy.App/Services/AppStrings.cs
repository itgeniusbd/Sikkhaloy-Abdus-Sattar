    public static string Get(string language, string key, params object[] args)
    {
        var table = string.Equals(language, "bn", StringComparison.OrdinalIgnoreCase) ? Bn : En;
        if (!table.TryGetValue(key, out var value) && !En.TryGetValue(key, out value))
            value = key;
        return args.Length == 0 ? value : string.Format(value, args);
    }

    public static string GetOr(string language, string key, string fallback)
    {
        var table = string.Equals(language, "bn", StringComparison.OrdinalIgnoreCase) ? Bn : En;
        if (table.TryGetValue(key, out var value))
            return value;
        if (En.TryGetValue(key, out value))
            return value;
        return fallback;
    }
