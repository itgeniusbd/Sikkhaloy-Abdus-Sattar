function getPath(obj, key) {
  return key.split('.').reduce((acc, part) => (acc == null ? acc : acc[part]), obj)
}

export function translate(lang, key, vars) {
  let text = getPath(translations[lang], key)
  if (text == null) text = getPath(translations.en, key)
  if (text == null) return key
  if (vars) {
    return String(text).replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? '' : vars[name]))
  }
  return text
}

export function mapLabel(lang, group, value) {
  if (!value) return value
  if (lang !== 'bn') return value
  return translations.bn[group]?.[value] || featureBn[value] || value
}

export function preferBn(lang, stored, englishDefault, bangla) {
  if (lang !== 'bn' || !bangla) return stored || englishDefault
  if (!stored || stored === englishDefault) return bangla
  return stored
}
